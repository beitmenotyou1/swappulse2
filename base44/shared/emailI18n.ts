// SwapPulse email i18n — user-facing email strings translated into the
// supported UI languages. Used by emailContent.ts builders so system emails
// render in the recipient's preferred language. English is the fallback.
// Card data (names, set names) is never translated here — cards always render
// in their native TCGDex language regardless of email locale.

export type EmailLocale = 'en' | 'ja' | 'zh' | 'ko' | 'fr' | 'de' | 'it' | 'es' | 'pt';

export function normalizeEmailLocale(locale: string | undefined | null): EmailLocale {
  if (!locale) return 'en';
  const two = String(locale).slice(0, 2).toLowerCase();
  const map: Record<string, EmailLocale> = {
    en: 'en', ja: 'ja', jp: 'ja', zh: 'zh', ko: 'ko',
    fr: 'fr', de: 'de', it: 'it', es: 'es', pt: 'pt',
  };
  return map[two] || 'en';
}

