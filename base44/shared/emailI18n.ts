const STRINGS: Record<EmailLocale, StringMap> = { en, ja, zh, ko, fr: en, de: en, it: en, es: en, pt: en };

export function t(locale: EmailLocale, key: string, params?: Record<string, string | number>): string {
  const dict = STRINGS[locale] || en;
  let s = dict[key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return s;
}